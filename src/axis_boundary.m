function pw = axis_boundary(W1, gamma)
  % Давление на оси симметрии (раздел 6.1): стенка с s_w = 0, волна C+ в ячейке 1.
  % За волной поток идёт вдоль оси, theta* = 0:
  %   theta_1 + f_1(p_w) = 0
  % Сводится к распаду разрыва с зеркальным отражением ячейки 1 относительно
  % оси: W_L = [p1, rho1, q1, -theta1], W_R = W1. Тогда theta_L = -theta_1,
  % f_L = f_R = f_1, и уравнение riemann_solve
  %   f_L + f_R - (theta_L - theta_R) = 2*(f_1 + theta_1) = 0
  % совпадает с условием на оси, а theta* = 0 по симметрии.
  %
  % Вход:
  %   W1    — вектор параметров в ячейке 1, прилегающей к оси:
  %           [p, rho, q, theta] — давление, плотность, модуль скорости и угол
  %           её наклона к оси x, рад;
  %           поток должен быть сверхзвуковым (M > 1)
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   pw    — давление на оси за волной C+ (скачком или волной разрежения),
  %           при котором поток разворачивается вдоль оси (theta* = 0)
  %
  % Ошибки (из riemann_solve):
  %   отход скачка от оси — требуемый поворот больше delta_max;
  %   образование вакуума — требуемый поворот в волне разрежения слишком велик.

  W0 = [W1(1), W1(2), W1(3), -W1(4)];   % зеркальная ячейка под осью
  [~, WRS] = riemann_solve(W0, W1, gamma);
  pw = WRS(1);
end
