function q = flow_speed(u, v)
  % Модуль скорости
  %
  % Вход:
  %   u — x-компонента скорости (скаляр или массив)
  %   v — y-компонента скорости (скаляр или массив того же размера, что u)
  %
  % Выход:
  %   q — модуль вектора скорости (u, v), q >= 0; массив того же размера,
  %       что u

  q = sqrt(u.^2 + v.^2);
end
