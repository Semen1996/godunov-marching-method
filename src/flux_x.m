function F = flux_x(p, rho, u, v, gamma)
  % Вектор потоков F через сечение x = const (раздел 1)
  %
  % Вход:
  %   p   — [n x 1] давление (каждая строка — отдельная ячейка)
  %   rho — [n x 1] плотность
  %   u   — [n x 1] x-компонента скорости
  %   v   — [n x 1] y-компонента скорости
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   F   — [n x 4] потоки массы, x-импульса, y-импульса и энергии через
  %         единицу площади сечения x = const:
  %         F = [rho*u, p + rho*u^2, rho*u*v, rho*u*H],
  %         H = gamma/(gamma-1)*p/rho + (u^2 + v^2)/2 — полная энтальпия.
  %         Обратное преобразование — recover.

  H = gamma/(gamma-1)*p./rho + 0.5*(u.^2 + v.^2);
  m = rho.*u;
  F = [m, p + m.*u, m.*v, m.*H];
end
