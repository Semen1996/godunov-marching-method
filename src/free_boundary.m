function thb = free_boundary(WN, pa, gamma)
  % свободная граница (раздел 6.3): волна C- в ячейке N, p* = p_a
  %
  % Вход:
  %   WN — вектор параметров в ячейке N, прилегающей к границе струи:
  %        [p, rho, q, theta] — давление, плотность, модуль скорости и угол
  %        её наклона к оси x, рад; поток должен быть сверхзвуковым (M > 1)
  %   pa — давление окружающей среды (давление за волной C- на границе)
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   thb — угол наклона границы струи к оси x в радианах — угол потока
  %         за волной C- (скачком при pa > p_N, волной разрежения при pa < p_N):
  %         thb = theta_N - f_N(pa)
  %
  % Ошибка, если pa превышает предельное давление за присоединённым косым
  % скачком (p_N * shock_rmax(M_N, gamma)) — отход скачка.
  thN = WN(4);
  MN = WN(3)/sound_speed(WN(1), WN(2), gamma);
  if pa > WN(1)*shock_rmax(MN, gamma)
    error('free_boundary: отход скачка на границе струи');
  end
  thb = thN - wave_f(pa, WN(1), MN, gamma);
end
