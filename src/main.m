% MAIN. Плоская нерасчётная сверхзвуковая струя.
%
% Струя с p_j/p_a > 1 истекает из плоского сопла шириной w_noz в покоящуюся
% среду с давлением p_a. Считается верхняя половина струи: снизу ось симметрии
% (стенка с s_w = 0, раздел 6.1), сверху свободная граница p = p_a (раздел 6.3).
% Расчёт маршевым методом Годунова с точным решением стационарной задачи
% о распаде разрыва (раздел 5), в том числе на оси и на свободной границе.

clear;

% --- параметры ---
gamma = 1.4;     % показатель адиабаты
M     = 2.0;     % число Маха струи на срезе
npr   = 2;       % нерасчётность p_j/p_a
N     = 100;     % число ячеек поперёк полуструи
kappa = 0.8;     % коэффициент запаса в условии на шаг
every = 1;       % печатать каждый every-й шаг (0 — не печатать)

% геометрия (размерная, м)
w_noz = 0.01;    % ширина половины сопла на срезе (от точки симметрии до кромки)
x_len = 0.2;     % длина расчётной области вдоль оси

% Безразмерные величины
y_noz = 1;                 % безразмерная полуширина сопла
x_end = x_len/w_noz;       % безразмерная длина области

pa = 1;                    % безразмерное внешнее давление
pj = npr*pa;
rhoj = 1;
aj = sqrt(gamma*pj/rhoj);  % безразмерное скорость звука
uj = M*aj;

% --- маршевый метод Годунова ---
tic;

p = pj*ones(N, 1);
rho = rhoj*ones(N, 1);
u = uj*ones(N, 1);
v = zeros(N, 1);

eta = linspace(0, 1, N+1)';        % равномерное распределение узлов
x = 0;  ye = y_noz;                % на срезе верхняя граница — кромка сопла
y = eta*ye;                        % нижняя граница — ось, y_w = 0


X = [];  YE = [];  MC = [];  YC = [];
n = 0;
while true
  % 1. параметры в ячейках
  c = sound_speed(p, rho, gamma);

  if any(u <= c)
    error('main: u <= c при x = %.4f, маршевый метод неприменим', x);
  end

  % 2. точные распады на внутренних гранях 3/2 ... N-1/2
  W = [p, rho, flow_speed(u, v), flow_angle(u, v)];   % [p, rho, q, theta]
  WL = W(1:N-1, :);
  WR = W(2:N, :);
  [WLS, WRS] = riemann_solve(WL, WR, gamma);


  % ось симметрии (раздел 6.1): theta_1 + f_1(p_w) = 0
  pw = axis_boundary(W(1, :), gamma);

  % свободная граница (раздел 6.3): theta_b = theta_N - f_N(p_a)
  thb = free_boundary(W(N, :), pa, gamma);
  sb = tan(thb);

  n = n + 1;
  X(n, 1) = x;  YE(n, 1) = ye;
  MC(n, :) = mach_number(p, rho, u, v, gamma)';  YC(n, :) = 0.5*(y(1:N) + y(2:N+1))';
  if x >= x_end - 1e-12
    break;
  end

  % 3. шаг (априорная оценка раздела 7)
  hc = diff(y);
  q2 = u.^2 + v.^2;
  dx = kappa*min(hc.*(u.^2 - c.^2)./(2*c.*sqrt(q2 - c.^2)));
  dx = min(dx, x_end - x);

  % 4. новый слой
  yen = ye + dx*sb;
  yn = eta*yen;
  s = (yn - y)/dx;
  hn = diff(yn);

  % 5–6. потоки через грани
  Phi = zeros(N+1, 4);
  Phi(1, :) = [0, 0, pw, 0];                   % ось симметрии, s_w = 0
  Phi(2:N, :) = riemann_flux(WL, WR, WLS, WRS, s(2:N), gamma);
  Phi(N+1, :) = [0, -s(N+1)*pa, pa, 0];        % свободная граница

  % 7. схема 3.2
  F = flux_x(p, rho, u, v, gamma);
  Fn = (hc.*F - dx*(Phi(2:N+1, :) - Phi(1:N, :)))./hn;

  % 8. восстановление параметров
  [p, rho, u, v, Dmin] = recover(Fn, gamma);
  if Dmin < 0
    error('main: D < 0 при x = %.4f (запирание, слишком большой шаг?)', x + dx);
  end

  x = x + dx;  ye = yen;  y = yn;
  if every > 0 && mod(n, every) == 0
    fprintf('шаг %6d   x = %9.5f   dx = %.3e   y_e = %.5f\n', n, x, dx, ye);
  end
end

fprintf('Годунов (точный распад): N = %d, шагов %d, время %.1f с\n', N, numel(X) - 1, toc);
plot_results(X, YE, YC, MC, npr, M);
