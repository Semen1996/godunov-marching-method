function w = prandtl_meyer_angle(M, gamma)
  % функция Прандтля–Майера omega(M) (раздел 5.3)
  %
  % Входные аргументы:
  %   M - число Маха (скаляр или массив, вычисление поэлементное);
  %       при M <= 1 функция возвращает 0
  %   gamma - показатель адиабаты
  %
  % Выходные аргументы:
  %   w - угол Прандтля–Майера omega(M) в радианах,
  %       массив того же размера, что и M
  k = sqrt((gamma+1)/(gamma-1));
  t = sqrt(max(M.^2 - 1, 0));
  w = k*atan(t/k) - atan(t);
end
