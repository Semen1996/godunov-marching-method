function Phi = riemann_flux(WL, WR, WLS, WRS, s, gamma)
  % поток через грань по решению задачи о распаде разрыва (раздел 5.6)
  %
  % Грань — луч xi = s из точки распада. Решение автомодельно, вдоль луча
  % состояние постоянно; по углу луча выбирается одна из зон
  %   L | волна C- | L* | линия скольжения | R* | волна C+ | R
  % (волна — скачок или веер разрежения; внутри веера состояние находится
  % из инварианта theta -/+ omega(M)), и по состоянию в ней считается поток.
  % Положение волн хранится углами (а не наклонами tg), чтобы сравнение
  % с лучом грани было однозначным.
  %
  % Вход:
  %   WL  — [n x 4] параметры нижнего потока [p, rho, q, theta]: давление,
  %         плотность, модуль скорости и угол её наклона к оси x, рад
  %         (каждая строка — отдельная грань, n граней считаются векторно);
  %         поток должен быть сверхзвуковым (M > 1)
  %   WR  — [n x 4] параметры верхнего потока [p, rho, q, theta], M > 1
  %   WLS — [n x 4] состояние за волной C- (снизу от линии скольжения),
  %         [p*, rho, q, theta*]
  %   WRS — [n x 4] состояние за волной C+ (сверху от линии скольжения),
  %         [p*, rho, q, theta*];
  %         [WLS, WRS] = riemann_solve(WL, WR, gamma) для тех же WL, WR
  %   s   — [n x 1] наклон грани dy/dx (тангенс угла наклона к оси x);
  %         на грани с s = tg(theta*) берётся состояние WLS
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   Phi — [n x 4] поток через грань, отнесённый к единице длины по x,
  %         Phi = G - s*F = [m, m*u - s*p, m*v + p, m*H], m = rho*(v - s*u):
  %         потоки массы, x- и y-импульса и энергии (см. face_flux).
  %         Полная энтальпия H берётся из исходного потока с той же стороны
  %         от линии скольжения (H_L или H_R) — в волнах она сохраняется.

  phi = atan(s);
  thL = WL(:,4);  thR = WR(:,4);  thS = WLS(:,4);
  ML = state_mach(WL, gamma);    MR = state_mach(WR, gamma);
  MLS = state_mach(WLS, gamma);  MRS = state_mach(WRS, gamma);
  HL = state_enthalpy(WL, gamma);  HR = state_enthalpy(WR, gamma);

  % углы волн: L1 <= L2 <= theta* <= R1 <= R2 (для скачка L1 = L2, R1 = R2)
  aL1 = thL - asin(1./ML);   aL2 = thS - asin(1./MLS);    % веер: голова, хвост
  aR1 = thS + asin(1./MRS);  aR2 = thR + asin(1./MR);     % веер: хвост, голова
  pS = WLS(:,1);  pL = WL(:,1);  pR = WR(:,1);
  k = pS > pL;
  aL1(k) = thL(k) - shock_beta(pS(k)./pL(k), ML(k), gamma);  aL2(k) = aL1(k);
  k = pS > pR;
  aR2(k) = thR(k) + shock_beta(pS(k)./pR(k), MR(k), gamma);  aR1(k) = aR2(k);

  W = WRS;  H = HR;
  k = phi <= thS;  W(k,:) = WLS(k,:);  H(k) = HL(k);
  k = phi <= aL1;  W(k,:) = WL(k,:);
  k = phi >= aR2;  W(k,:) = WR(k,:);
  k = find(phi > aL1 & phi < aL2);
  if ~isempty(k)
    W(k,:) = fan_state(WL(k,:), ML(k), MLS(k), thL(k), HL(k), phi(k), -1, gamma);
  end
  k = find(phi > aR1 & phi < aR2);
  if ~isempty(k)
    W(k,:) = fan_state(WR(k,:), MR(k), MRS(k), thR(k), HR(k), phi(k), +1, gamma);
  end
  q = W(:,3);  th = W(:,4);
  Phi = face_flux([W(:,1), W(:,2), q.*cos(th), q.*sin(th)], s, gamma, H);
end

function M = state_mach(W, gamma)
  % Число Маха по вектору параметров
  %
  % Вход:
  %   W — [n x 4] параметры потока [p, rho, q, theta]: давление, плотность,
  %       модуль скорости и угол её наклона к оси x, рад
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   M — [n x 1] число Маха, отношение модуля скорости q к скорости звука

  M = W(:,3)./sound_speed(W(:,1), W(:,2), gamma);
end

function H = state_enthalpy(W, gamma)
  % Полная энтальпия единицы массы по вектору параметров
  %
  % Вход:
  %   W — [n x 4] параметры потока [p, rho, q, theta]: давление, плотность,
  %       модуль скорости и угол её наклона к оси x, рад
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   H — [n x 1] полная энтальпия H = gamma/(gamma-1)*p/rho + q^2/2

  H = gamma/(gamma-1)*W(:,1)./W(:,2) + 0.5*W(:,3).^2;
end

function b = shock_beta(r, M, gamma)
  % Угол косого скачка к набегающему потоку по отношению давлений
  %
  % Вход:
  %   r — отношение давлений на скачке p2/p1, r >= 1 (массив)
  %   M — число Маха набегающего потока, M > 1 (массив того же размера, что r)
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   b — угол beta между фронтом скачка и вектором скорости набегающего
  %       потока в радианах, от угла Маха asin(1/M) при r = 1 до pi/2
  %       (прямой скачок); массив того же размера, что r:
  %         sin(beta)^2 = (1 + (gamma+1)/(2*gamma)*(r - 1))/M^2
  %       Синус ограничен единицей на случай ошибок округления вблизи
  %       прямого скачка.

  b = asin(min(sqrt(1 + (gamma+1)/(2*gamma)*(r - 1))./M, 1));
end

function W = fan_state(Wk, Mk, Mks, thk, Hk, phi, sg, gamma)
  % Состояние внутри веера разрежения на луче с углом phi
  %
  % Луч в веере — характеристика: phi = theta + sg*mu(M), mu = asin(1/M).
  % Вместе с инвариантом веера theta + sg*omega(M) = theta_k + sg*omega(M_k)
  % это даёт уравнение для числа Маха на луче
  %   omega(M) - mu(M) = sg*(theta_k - phi) + omega(M_k),
  % которое решается методом Ньютона с защитой делением пополам на отрезке
  % между M_k и M_k*. Затем theta = phi - sg*mu(M), давление и плотность —
  % по изоэнтропе от состояния k, скорость — из сохранения полной энтальпии.
  %
  % Вход:
  %   Wk  — [n x 4] параметры потока перед веером [p, rho, q, theta]:
  %         давление, плотность, модуль скорости и угол её наклона к оси x,
  %         рад (каждая строка — отдельный луч)
  %   Mk  — [n x 1] число Маха перед веером (на голове веера)
  %   Mks — [n x 1] число Маха за веером (на хвосте веера); вместе с Mk
  %         задаёт отрезок поиска корня
  %   thk — [n x 1] угол наклона скорости перед веером, рад (theta из Wk)
  %   Hk  — [n x 1] полная энтальпия потока перед веером
  %   phi — [n x 1] угол наклона луча к оси x, рад; должен лежать между
  %         головой и хвостом веера
  %   sg  — семейство волны (скаляр): -1 — веер C- (в нижнем потоке),
  %         +1 — веер C+ (в верхнем потоке)
  %   gamma — показатель адиабаты (скаляр)
  %
  % Выход:
  %   W   — [n x 4] состояние на луче [p, rho, q, theta]

  rhs = sg*(thk - phi) + prandtl_meyer_angle(Mk, gamma);
  lo = min(Mk, Mks);  hi = max(Mk, Mks);
  M = 0.5*(lo + hi);
  for it = 1:60
    G = prandtl_meyer_angle(M, gamma) - asin(1./M) - rhs;
    lo(G < 0) = M(G < 0);
    hi(G > 0) = M(G > 0);
    t = sqrt(M.^2 - 1);
    dG = t./(M.*(1 + 0.5*(gamma-1)*M.^2)) + 1./(M.*t);
    Mn = M - G./dG;
    k = ~(Mn > lo & Mn < hi);
    Mn(k) = 0.5*(lo(k) + hi(k));
    dM = max(abs(Mn - M)./M);
    M = Mn;
    if dM < 1e-12
      break;
    end
  end
  th = phi - sg*asin(1./M);
  pk = Wk(:,1);  rhok = Wk(:,2);
  p = pk.*((1 + 0.5*(gamma-1)*Mk.^2)./(1 + 0.5*(gamma-1)*M.^2)).^(gamma/(gamma-1));
  rho = rhok.*(p./pk).^(1/gamma);
  q = sqrt(2*Hk - 2*gamma/(gamma-1)*p./rho);
  W = [p, rho, q, th];
end
